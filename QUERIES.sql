CREATE DATABASE Marketing_Analytics;

CREATE TABLE marketing_data (
    id INT PRIMARY KEY,
    date DATETIME,
    region VARCHAR(20),
    channel VARCHAR(30),
    product_category VARCHAR(50),
    customer_segment VARCHAR(30),

    ad_spend DECIMAL(12,2),
    price DECIMAL(10,2),
    discount_rate DECIMAL(5,2),
    market_reach DECIMAL(10,2),

    impressions INT,
    click_through_rate DECIMAL(6,2),
    competition_index DECIMAL(6,2),
    seasonality_index DECIMAL(6,2),
    campaign_duration_days INT,

    customer_lifetime_value DECIMAL(12,2),
    sales_revenue DECIMAL(12,2)
);











