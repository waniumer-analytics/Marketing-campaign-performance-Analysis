## Q9:- Find campaigns whose revenue is above the average revenue of their marketing channel using a CTE.

WITH ChannelAverage AS
(
    SELECT
        channel,
        AVG(sales_revenue) AS Avg_Revenue
    FROM marketing_data
    GROUP BY channel
)

SELECT
    m.id,
    m.channel,
    m.sales_revenue
FROM marketing_data m
JOIN ChannelAverage c
ON m.channel = c.channel
WHERE m.sales_revenue > c.Avg_Revenue;

